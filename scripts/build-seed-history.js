#!/usr/bin/env node
/* Builds travel-expense-tracker/seed-history.js from every seed.js version that
 * has shipped, so the app can update a phone's saved plan safely:
 * a value is only replaced if it still equals something a previous version shipped
 * (i.e. the user never edited it), and only items that are new since the phone's
 * version get added.
 *
 * Usage (from the repo root), listing shipped seed versions oldest first:
 *   node scripts/build-seed-history.js <commit-of-v1> <commit-of-v2> ...
 * Each argument is a git commit whose travel-expense-tracker/seed.js is that version.
 */
const { execSync } = require('child_process');
const vm = require('vm');
const fs = require('fs');
const path = require('path');

const FIELDS = ['from', 'to', 'fromLat', 'fromLng', 'toLat', 'toLng', 'country', 'startTz', 'arriveTz', 'distanceMi',
  'distanceNote', 'driveHours', 'start', 'arrive', 'route', 'routeVia', 'tzNote', 'notes', 'stops', 'fuelStops',
  'fuelSearch', 'foodSearch', 'overnightSearch', 'links'];
const TOLL_FIELDS = ['name', 'highway', 'estAmount', 'currency', 'kind', 'optional', 'note', 'matchHighway', 'leg'];
const V2_TOLL_ORDER = ['out-colombia', 'out-85d', 'out-40d', 'out-57d', 'out-libqro', 'out-45d'];
const V2_DOC_ORDER = ['passports', 'license', 'registration', 'tip', 'insurance', 'usd', 'mxn', 'tag', 'charger', 'papermap'];

function loadSeed(commit) {
  const src = execSync(`git show ${commit}:travel-expense-tracker/seed.js`, { encoding: 'utf8' });
  const ctx = { window: {} };
  vm.runInNewContext(src, ctx);
  const s = ctx.window.SEED;
  const version = s.version || 1;
  // Version 1 had no keys: give it the keys later versions use.
  const days = s.days.map((d, i) => Object.assign({ key: d.key || 'out' + (i + 1) }, d));
  const tolls = s.expectedTolls.map((e, i) => Object.assign({ key: e.key || V2_TOLL_ORDER[i] }, e));
  const docs = s.docs.map((d, i) => (d.key ? d : { key: V2_DOC_ORDER[i], text: d }));
  return { version, days, tomorrow: s.tomorrow, tolls, budget: s.budget, docs };
}

const J = (v) => JSON.stringify(v === undefined ? null : v);
const push = (obj, k, f, v) => { obj[k] = obj[k] || {}; obj[k][f] = obj[k][f] || []; if (!obj[k][f].includes(J(v))) obj[k][f].push(J(v)); };

const commits = process.argv.slice(2);
if (!commits.length) { console.error('List the commits of every shipped seed version, oldest first.'); process.exit(1); }
const H = { versions: {}, days: {}, notes: {}, notesByVersion: {}, tolls: {}, budget: {}, docs: {}, v1TollNames: {}, v1Docs: {} };
for (const c of commits) {
  const s = loadSeed(c);
  H.versions[s.version] = { days: s.days.map((d) => d.key), tolls: s.tolls.map((e) => e.key), docs: s.docs.map((d) => d.key) };
  s.days.forEach((d, i) => {
    FIELDS.forEach((f) => push(H.days, d.key, f, d[f]));
    H.notes[d.key] = H.notes[d.key] || [];
    (s.tomorrow[i] || []).forEach((n) => { if (!H.notes[d.key].includes(n.en)) H.notes[d.key].push(n.en); });
    H.notesByVersion[s.version] = H.notesByVersion[s.version] || {};
    H.notesByVersion[s.version][d.key] = (s.tomorrow[i] || []).map((n) => n.en);
  });
  s.tolls.forEach((e) => TOLL_FIELDS.forEach((f) => push(H.tolls, e.key, f, e[f])));
  s.budget.forEach((b) => ['amount', 'currency', 'note'].forEach((f) => push(H.budget, b.cat, f, b[f])));
  s.docs.forEach((d) => push(H.docs, d.key, 'text', d.text));
  if (s.version === 1) {
    s.tolls.forEach((e) => { H.v1TollNames[e.name] = e.key; });
    s.docs.forEach((d) => { H.v1Docs[d.text.en] = d.key; });
  }
}
const out = path.join(__dirname, '../travel-expense-tracker/seed-history.js');
fs.writeFileSync(out, '/* Generated by scripts/build-seed-history.js. Do not edit by hand. */\nwindow.SEED_HISTORY = ' + JSON.stringify(H) + ';\n');
console.log('Wrote', out, 'versions:', Object.keys(H.versions).join(', '));
